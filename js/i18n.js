  getLang: function () {
    return localStorage.getItem('lang') || 'en';
  },

  t: function (key, lang) {
    lang = lang || this.getLang();
    return this.translations[lang][key] || this.translations.en[key] || key;
  },

  apply: function (lang) {
    lang = lang || this.getLang();
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;

    var strings = this.translations[lang];
    var page = document.body.dataset.page;

    if (page && strings['meta.' + page + '.title']) {
      document.title = strings['meta.' + page + '.title'];
    }

    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && page && strings['meta.' + page + '.description']) {
      metaDesc.setAttribute('content', strings['meta.' + page + '.description']);
    }

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (strings[key]) {
        el.textContent = strings[key];
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (strings[key]) {
        el.innerHTML = strings[key];
      }
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-alt');
      if (strings[key]) {
        el.setAttribute('alt', strings[key]);
      }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      if (strings[key]) {
        el.setAttribute('title', strings[key]);
      }
    });

    document.querySelectorAll('[data-i18n-src]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-src');
      var localized = strings[key + '.' + lang] || strings[key + '.en'] || strings[key];
      if (localized) {
        el.setAttribute('src', localized);
      }
    });

    var year = new Date().getFullYear();
    var copyEl = document.querySelector('[data-i18n="footer.copy"]');
    if (copyEl && strings['footer.copy']) {
      copyEl.textContent = strings['footer.copy'].replace('{year}', year);
    }

    var mapFrame = document.getElementById('footer-map');
    if (mapFrame) {
      mapFrame.src = 'https://maps.google.com/maps?q=400+Rue+Saint-Henri,+Montréal,+QC+H3C+2P5&hl=' + lang + '&z=16&output=embed';
    }

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.classList.toggle('active', btn.dataset.lang === lang);
      btn.setAttribute('aria-pressed', btn.dataset.lang === lang ? 'true' : 'false');
    });

    var navToggle = document.querySelector('.nav-toggle');
    if (navToggle && !document.querySelector('.main-nav.open')) {
      navToggle.setAttribute('aria-label', strings['nav.menu.open']);
    }

    if (window.SalonSeo) {
      SalonSeo.apply(lang);
    }
  }
